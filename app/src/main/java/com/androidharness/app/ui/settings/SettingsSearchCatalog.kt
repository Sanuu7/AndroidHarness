/*
 * Every setting the search can land on, one entry per control.
 *
 * An entry's anchor is the string resource the control renders as its label,
 * and the control marks itself with that same id (SettingsAnchor or
 * Modifier.settingsAnchor), so a result scrolls to it and tints it. Shared rows
 * such as SettingRow, SettingsDisclosure and the switch rows match by label on
 * their own. A control inside a collapsed section lists that section's title in
 * `within`, and the section opens on arrival.
 *
 * Keywords stay in English: they are search vocabulary, not UI copy.
 */

